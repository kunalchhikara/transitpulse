"""DE-02: the deterministic simulator core engine.

Produces normal (non-incident) `simulator.schemas.telemetry.TelemetryEvent`
streams for the vehicles/routes/stops generated by DE-01
(`simulator.reference.generator.generate_reference_dataset`), driven by this
package's own `GeneratorConfig` (emission rate, movement dynamics, normal
value ranges) per `PROJECT.md` section 19.

Public API:

- `GeneratorConfig` / `load_generator_config` (`simulator.generator.config`):
  externalized emission-rate/movement/value-range configuration.
- `TelemetryGenerator` (`simulator.generator.core`): deterministic event
  producer -- same seed + config -> byte-identical event sequence.
- `run` / `RunSummary` (`simulator.generator.runner`): the real-time-paced
  (or test-fast-forwarded, via `Clock`) emission loop with graceful-shutdown
  support.
- `SystemClock` / `FakeClock` (`simulator.generator.clock`): injectable time
  source -- `FakeClock` lets tests exercise emission-rate pacing without any
  real `time.sleep`.
- `configure_logging` (`simulator.generator.logging_setup`): structured
  JSON-lines logging, isolated from the stdout event stream.

Incident scenarios (PROJECT.md section 13) are explicitly out of scope here
-- see `docs/BACKLOG.md` DE-03.
"""

